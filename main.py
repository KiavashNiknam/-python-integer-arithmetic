a = int(input("Enter first number (a): "))
b = int(input("Enter second number (b): "))

total = a + b
diff = a - b
prod = a * b
quot = a // b
rem = a % b
exp = a ** b

print(f"{a} + {b} = {total}")
print(f"{a} - {b} = {diff}")
print(f"{a} * {b} = {prod}")
print(f"{a} // {b} = {quot}")
print(f"{a} % {b} = {rem}")
print(f"{a} ** {b} = {exp}")
